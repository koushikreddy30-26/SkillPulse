
import json
import os
import sqlite3
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

DB_PATH = Path(__file__).resolve().parent / "skillpulse.db"


def _uses_postgres():
    return bool(os.environ.get("DATABASE_URL"))


def get_connection():
    """Use PostgreSQL in deployment and SQLite for local development."""
    if _uses_postgres():
        url = os.environ["DATABASE_URL"]

        if url.startswith("postgres://"):
            url = url.replace("postgres://", "postgresql://", 1)

        return psycopg.connect(url, row_factory=dict_row)

    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def _add_user_id_column(conn, table_name):
    if _uses_postgres():
        columns = {
            row["column_name"]
            for row in conn.execute(
                """
                SELECT column_name
                FROM information_schema.columns
                WHERE table_schema = 'public' AND table_name = %s
                """,
                (table_name,),
            ).fetchall()
        }

        if "user_id" not in columns:
            conn.execute(
                f'ALTER TABLE "{table_name}" ADD COLUMN user_id BIGINT'
            )
        return

    columns = {
        row["name"]
        for row in conn.execute(
            f"PRAGMA table_info({table_name})"
        ).fetchall()
    }

    if "user_id" not in columns:
        conn.execute(
            f"ALTER TABLE {table_name} ADD COLUMN user_id INTEGER"
        )


def _execute(conn, postgres_sql, sqlite_sql, params=()):
    if _uses_postgres():
        return conn.execute(postgres_sql, params)
    return conn.execute(sqlite_sql, params)


def init_db():
    """Initialize the selected database without deleting existing records."""
    with get_connection() as conn:
        if _uses_postgres():
            conn.execute("""
                CREATE TABLE IF NOT EXISTS profiles (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL DEFAULT 'Learner',
                    career_goal TEXT NOT NULL,
                    current_skills TEXT NOT NULL,
                    required_skills TEXT NOT NULL,
                    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                    user_id BIGINT
                )
            """)

            conn.execute("""
                CREATE TABLE IF NOT EXISTS saved_plans (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    profile_id BIGINT,
                    career_goal TEXT NOT NULL,
                    plan_json TEXT NOT NULL,
                    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                    user_id BIGINT
                )
            """)

            conn.execute("""
                CREATE TABLE IF NOT EXISTS saved_recommendations (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    profile_id BIGINT,
                    target_skill TEXT NOT NULL,
                    recommendations_json TEXT NOT NULL,
                    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                    user_id BIGINT
                )
            """)
        else:
            conn.execute("""
                CREATE TABLE IF NOT EXISTS profiles (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    name TEXT NOT NULL DEFAULT 'Learner',
                    career_goal TEXT NOT NULL,
                    current_skills TEXT NOT NULL,
                    required_skills TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    user_id INTEGER
                )
            """)

            conn.execute("""
                CREATE TABLE IF NOT EXISTS saved_plans (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    profile_id INTEGER,
                    career_goal TEXT NOT NULL,
                    plan_json TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    user_id INTEGER
                )
            """)

            conn.execute("""
                CREATE TABLE IF NOT EXISTS saved_recommendations (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    profile_id INTEGER,
                    target_skill TEXT NOT NULL,
                    recommendations_json TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    user_id INTEGER
                )
            """)

        for table in (
            "profiles",
            "saved_plans",
            "saved_recommendations",
        ):
            _add_user_id_column(conn, table)
            conn.execute(
                f"CREATE INDEX IF NOT EXISTS idx_{table}_user_id "
                f"ON {table}(user_id)"
            )


def save_profile(name, career_goal, current_skills, required_skills, user_id):
    with get_connection() as conn:
        cursor = _execute(
            conn,
            """
            INSERT INTO profiles
                (name, career_goal, current_skills, required_skills, user_id)
            VALUES (%s, %s, %s, %s, %s)
            RETURNING id
            """,
            """
            INSERT INTO profiles
                (name, career_goal, current_skills, required_skills, user_id)
            VALUES (?, ?, ?, ?, ?)
            """,
            (name, career_goal, current_skills, required_skills, user_id),
        )

        if _uses_postgres():
            return cursor.fetchone()["id"]
        return cursor.lastrowid


def list_profiles(user_id):
    with get_connection() as conn:
        rows = _execute(
            conn,
            """
            SELECT id, name, career_goal, current_skills,
                   required_skills, created_at::text AS created_at, user_id
            FROM profiles WHERE user_id = %s ORDER BY id DESC
            """,
            """
            SELECT * FROM profiles WHERE user_id = ? ORDER BY id DESC
            """,
            (user_id,),
        ).fetchall()

        return [dict(row) for row in rows]


def profile_belongs_to_user(profile_id, user_id):
    if profile_id is None:
        return True

    with get_connection() as conn:
        row = _execute(
            conn,
            "SELECT id FROM profiles WHERE id = %s AND user_id = %s",
            "SELECT id FROM profiles WHERE id = ? AND user_id = ?",
            (profile_id, user_id),
        ).fetchone()

        return row is not None


def save_plan(profile_id, career_goal, plan, user_id):
    with get_connection() as conn:
        cursor = _execute(
            conn,
            """
            INSERT INTO saved_plans
                (profile_id, career_goal, plan_json, user_id)
            VALUES (%s, %s, %s, %s)
            RETURNING id
            """,
            """
            INSERT INTO saved_plans
                (profile_id, career_goal, plan_json, user_id)
            VALUES (?, ?, ?, ?)
            """,
            (profile_id, career_goal, json.dumps(plan), user_id),
        )

        if _uses_postgres():
            return cursor.fetchone()["id"]
        return cursor.lastrowid


def list_plans(user_id):
    with get_connection() as conn:
        rows = _execute(
            conn,
            """
            SELECT id, profile_id, career_goal, plan_json,
                   created_at::text AS created_at, user_id
            FROM saved_plans WHERE user_id = %s ORDER BY id DESC
            """,
            """
            SELECT * FROM saved_plans WHERE user_id = ? ORDER BY id DESC
            """,
            (user_id,),
        ).fetchall()

        result = []
        for row in rows:
            item = dict(row)
            item["plan"] = json.loads(item.pop("plan_json"))
            result.append(item)

        return result


