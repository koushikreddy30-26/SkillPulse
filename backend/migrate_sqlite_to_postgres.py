
import os
import sqlite3
import sys
from datetime import datetime, timezone
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

BACKEND_DIR = Path(__file__).resolve().parent
AUTH_DB_PATH = BACKEND_DIR / "skillpulse_accounts.db"
APP_DB_PATH = BACKEND_DIR / "skillpulse.db"

TABLE_COLUMNS = {
    "users": [
        "id", "name", "email", "password_hash", "created_at"
    ],
    "profiles": [
        "id", "name", "career_goal", "current_skills",
        "required_skills", "created_at", "user_id"
    ],
    "saved_plans": [
        "id", "profile_id", "career_goal", "plan_json",
        "created_at", "user_id"
    ],
    "saved_recommendations": [
        "id", "profile_id", "target_skill",
        "recommendations_json", "created_at", "user_id"
    ],
}


def get_database_url():
    url = os.environ.get("DATABASE_URL")
    if not url:
        raise RuntimeError(
            "DATABASE_URL is not set. Migration was not started."
        )

    if url.startswith("postgres://"):
        url = url.replace("postgres://", "postgresql://", 1)

    if url.startswith("postgresql://") and "sslmode=" not in url:
        separator = "&" if "?" in url else "?"
        url += f"{separator}sslmode=require"

    return url


def read_rows(db_path, table):
    if not db_path.exists():
        raise FileNotFoundError(f"Missing SQLite database: {db_path}")

    uri = f"{db_path.resolve().as_uri()}?mode=ro"

    with sqlite3.connect(uri, uri=True) as source:
        source.row_factory = sqlite3.Row
        exists = source.execute(
            "SELECT 1 FROM sqlite_master "
            "WHERE type='table' AND name=?",
            (table,),
        ).fetchone()

        if not exists:
            raise RuntimeError(
                f"Required SQLite table '{table}' is missing."
            )

        columns = {
            row[1] for row in
            source.execute(f'PRAGMA table_info("{table}")')
        }
        missing = set(TABLE_COLUMNS[table]) - columns
        if missing:
            raise RuntimeError(
                f"SQLite table '{table}' lacks columns: {sorted(missing)}"
            )

        return [
            dict(row)
            for row in source.execute(f'SELECT * FROM "{table}"')
        ]


def normalize(value, column):
    if value is None:
        return None

    if column != "created_at":
        return value

    if isinstance(value, datetime):
        dt = value
    elif isinstance(value, str):
        try:
            dt = datetime.fromisoformat(value.replace("Z", "+00:00"))
        except ValueError:
            # Preserve nonstandard legacy timestamps for exact comparison.
            return value
    else:
        return value

    # Treat timezone-naive legacy timestamps as UTC for comparison.
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)

    return dt.astimezone(timezone.utc)


def create_schema(conn):
    # Deliberately do not add ownership foreign keys: legacy records
    # with NULL user_id must remain valid and unchanged.
    conn.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            email TEXT NOT NULL,
            password_hash TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
    """)
    conn.execute("""
        CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower
        ON users (LOWER(email))
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS profiles (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL DEFAULT 'Learner',
            career_goal TEXT NOT NULL,
            current_skills TEXT NOT NULL,
            required_skills TEXT NOT NULL,
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
            user_id BIGINT
        )
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS saved_plans (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            profile_id BIGINT,
            career_goal TEXT NOT NULL,
            plan_json TEXT NOT NULL,
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
            user_id BIGINT
        )
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS saved_recommendations (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            profile_id BIGINT,
            target_skill TEXT NOT NULL,
            recommendations_json TEXT NOT NULL,
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
            user_id BIGINT
        )
    """)
    conn.execute("""
        CREATE INDEX IF NOT EXISTS idx_profiles_user_id
        ON profiles(user_id)
    """)
    conn.execute("""
        CREATE INDEX IF NOT EXISTS idx_saved_plans_user_id
        ON saved_plans(user_id)
    """)
    conn.execute("""
        CREATE INDEX IF NOT EXISTS idx_saved_recommendations_user_id
        ON saved_recommendations(user_id)
    """)


def verify_schema(conn, table):
    actual = {
        row["column_name"]
        for row in conn.execute("""
            SELECT column_name
            FROM information_schema.columns
            WHERE table_schema = 'public' AND table_name = %s
        """, (table,)).fetchall()
    }
    missing = set(TABLE_COLUMNS[table]) - actual
    if missing:
        raise RuntimeError(
            f"PostgreSQL table '{table}' lacks columns: {sorted(missing)}"
        )


def insert_and_verify(conn, table, rows):
    columns = TABLE_COLUMNS[table]
    quoted = ", ".join(f'"{c}"' for c in columns)
    placeholders = ", ".join(["%s"] * len(columns))

    for source_row in rows:
        values = [source_row.get(c) for c in columns]
        existing = conn.execute(
            f'SELECT {quoted} FROM "{table}" WHERE id = %s',
            (source_row["id"],),
        ).fetchone()

        if existing is None:
            conn.execute(
                f'INSERT INTO "{table}" ({quoted}) '
                f'VALUES ({placeholders})',
                values,
            )
        else:
            differences = [
                c for c in columns
                if normalize(existing[c], c)
                != normalize(source_row.get(c), c)
            ]
            if differences:
                raise RuntimeError(
                    f"Conflict in {table} id={source_row['id']}; "
                    f"different fields: {differences}. "
                    "Transaction will be rolled back."
                )

    # Re-read every source record and verify every migrated field.
    for source_row in rows:
        actual = conn.execute(
            f'SELECT {quoted} FROM "{table}" WHERE id = %s',
            (source_row["id"],),
        ).fetchone()

        if actual is None:
            raise RuntimeError(
                f"Verification failed: {table} id={source_row['id']} missing."
            )

        differences = [
            c for c in columns
            if normalize(actual[c], c)
            != normalize(source_row.get(c), c)
        ]
        if differences:
            raise RuntimeError(
                f"Verification failed for {table} id={source_row['id']}: "
                f"{differences}"
            )


def reset_identity_sequence(conn, table):
    sequence = conn.execute(
        "SELECT pg_get_serial_sequence(%s, 'id') AS sequence",
        (f"public.{table}",),
    ).fetchone()["sequence"]

    if not sequence:
        raise RuntimeError(f"No identity sequence found for {table}")

    max_id = conn.execute(
        f'SELECT MAX(id) AS max_id FROM "{table}"'
    ).fetchone()["max_id"]

    if max_id is None:
        conn.execute("SELECT setval(%s, 1, false)", (sequence,))
    else:
        conn.execute("SELECT setval(%s, %s, true)", (sequence, max_id))


def migrate():
    # Read source files before opening a PostgreSQL connection.
    users = read_rows(AUTH_DB_PATH, "users")
    profiles = read_rows(APP_DB_PATH, "profiles")
    plans = read_rows(APP_DB_PATH, "saved_plans")
    recommendations = read_rows(APP_DB_PATH, "saved_recommendations")

    datasets = {
        "users": users,
        "profiles": profiles,
        "saved_plans": plans,
        "saved_recommendations": recommendations,
    }

    for table, rows in datasets.items():
        ids = [row["id"] for row in rows]
        if len(ids) != len(set(ids)):
            raise RuntimeError(f"Duplicate IDs in source table '{table}'.")

    print("SQLite source counts:")
    for table, rows in datasets.items():
        print(f"  {table}: {len(rows)}")

    # Preserve NULL ownership; don't infer or assign account IDs.
    for table in ("profiles", "saved_plans", "saved_recommendations"):
        null_count = sum(row.get("user_id") is None for row in datasets[table])
        print(f"  {table} with NULL user_id: {null_count}")

    url = get_database_url()

    # Schema changes and data import run in one PostgreSQL transaction.
    with psycopg.connect(url, row_factory=dict_row) as conn:
        create_schema(conn)

        for table in TABLE_COLUMNS:
            verify_schema(conn, table)

        # Parent records first, then application records.
        for table in TABLE_COLUMNS:
            insert_and_verify(conn, table, datasets[table])

        for table in TABLE_COLUMNS:
            reset_identity_sequence(conn, table)

        print("\nVerified source records against PostgreSQL:")
        for table, source_rows in datasets.items():
            total = conn.execute(
                f'SELECT COUNT(*) AS total FROM "{table}"'
            ).fetchone()["total"]
            print(
                f"  {table}: {len(source_rows)} source records verified; "
                f"{total} total in PostgreSQL"
            )

    print("\nMigration completed; all source fields verified.")
    print("Original SQLite databases were read-only and unchanged.")


if __name__ == "__main__":
    try:
        migrate()
    except Exception as exc:
        print(f"\nMigration stopped: {exc}", file=sys.stderr)
        sys.exit(1)
