
import json
import os

import psycopg
from psycopg.rows import dict_row


def get_pg_connection():
    """Connect to the PostgreSQL database configured in the environment."""
    database_url = os.environ.get("DATABASE_URL")

    if not database_url:
        raise RuntimeError("DATABASE_URL is not configured.")

    if database_url.startswith("postgres://"):
        database_url = database_url.replace(
            "postgres://", "postgresql://", 1
        )

    return psycopg.connect(database_url, row_factory=dict_row)


def init_pg_db():
    """Create SkillPulse PostgreSQL tables and indexes."""
    with get_pg_connection() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                email TEXT NOT NULL,
                password_hash TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        # Match SQLite's case-insensitive email uniqueness.
        conn.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower
            ON users (LOWER(email))
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS profiles (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL DEFAULT 'Learner',
                career_goal TEXT NOT NULL,
                current_skills TEXT NOT NULL,
                required_skills TEXT NOT NULL,
                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                user_id BIGINT REFERENCES users(id)
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS saved_plans (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                profile_id BIGINT REFERENCES profiles(id),
                career_goal TEXT NOT NULL,
                plan_json TEXT NOT NULL,
                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                user_id BIGINT REFERENCES users(id)
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS saved_recommendations (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                profile_id BIGINT REFERENCES profiles(id),
                target_skill TEXT NOT NULL,
                recommendations_json TEXT NOT NULL,
                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                user_id BIGINT REFERENCES users(id)
            )
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_profiles_user_id
            ON profiles(user_id)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_saved_plans_user_id
            ON saved_plans(user_id)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_saved_recommendations_user_id
            ON saved_recommendations(user_id)
        """)


def _json_text(value):
    """Serialize values consistently for JSON-backed database columns."""
    return json.dumps(value)


def save_profile(
    name, career_goal, current_skills, required_skills, user_id
):
    with get_pg_connection() as conn:
        row = conn.execute("""
            INSERT INTO profiles (
                name, career_goal, current_skills,
                required_skills, user_id
            )
            VALUES (%s, %s, %s, %s, %s)
            RETURNING id
        """, (
            name,
            career_goal,
            current_skills,
            required_skills,
            user_id,
        )).fetchone()

        return row["id"]


def list_profiles(user_id):
    with get_pg_connection() as conn:
        rows = conn.execute("""
            SELECT id, name, career_goal, current_skills,
                   required_skills, created_at::text AS created_at,
                   user_id
            FROM profiles
            WHERE user_id = %s
            ORDER BY id DESC
        """, (user_id,)).fetchall()

        return [dict(row) for row in rows]


def profile_belongs_to_user(profile_id, user_id):
    if profile_id is None:
        return True

    with get_pg_connection() as conn:
        row = conn.execute("""
            SELECT 1
            FROM profiles
            WHERE id = %s AND user_id = %s
        """, (profile_id, user_id)).fetchone()

        return row is not None


def save_plan(profile_id, career_goal, plan, user_id):
    with get_pg_connection() as conn:
        row = conn.execute("""
            INSERT INTO saved_plans (
                profile_id, career_goal, plan_json, user_id
            )
            VALUES (%s, %s, %s, %s)
            RETURNING id
        """, (
            profile_id,
            career_goal,
            _json_text(plan),
            user_id,
        )).fetchone()

        return row["id"]


def list_plans(user_id):
    with get_pg_connection() as conn:
        rows = conn.execute("""
            SELECT id, profile_id, career_goal, plan_json,
                   created_at::text AS created_at, user_id
            FROM saved_plans
            WHERE user_id = %s
            ORDER BY id DESC
        """, (user_id,)).fetchall()

        result = []
        for row in rows:
            item = dict(row)
            item["plan"] = json.loads(item.pop("plan_json"))
            result.append(item)

        return result


def save_recommendations(
    profile_id, target_skill, recommendations, user_id
):
    with get_pg_connection() as conn:
        row = conn.execute("""
            INSERT INTO saved_recommendations (
                profile_id, target_skill,
                recommendations_json, user_id
            )
            VALUES (%s, %s, %s, %s)
            RETURNING id
        """, (
            profile_id,
            target_skill,
            _json_text(recommendations),
            user_id,
        )).fetchone()

        return row["id"]


def list_saved_recommendations(user_id):
    with get_pg_connection() as conn:
        rows = conn.execute("""
            SELECT id, profile_id, target_skill,
                   recommendations_json,
                   created_at::text AS created_at, user_id
            FROM saved_recommendations
            WHERE user_id = %s
            ORDER BY id DESC
        """, (user_id,)).fetchall()

        result = []
        for row in rows:
            item = dict(row)
            item["recommendations"] = json.loads(
                item.pop("recommendations_json")
            )
            result.append(item)

        return result
